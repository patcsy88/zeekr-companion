// Regenerates src/api.d.ts from the FastAPI OpenAPI schema.
//   node scripts/generate.mjs           write the file
//   node scripts/generate.mjs --check   write nothing; exit 1 if the committed file differs
// The schema comes from `python -m app.cli.export_openapi` (the live API does not serve it).
import { execFileSync } from "node:child_process";
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const pkg = resolve(here, "..");
const apiDir = resolve(pkg, "../../services/api");
const target = join(pkg, "src", "api.d.ts");
const check = process.argv.includes("--check");

const python =
  process.env.PYTHON ??
  [join(apiDir, ".venv", "bin", "python"), join(apiDir, ".venv", "Scripts", "python.exe")].find(
    existsSync,
  ) ??
  "python3";

const work = mkdtempSync(join(tmpdir(), "zc-shared-types-"));
try {
  const schema = execFileSync(python, ["-m", "app.cli.export_openapi"], {
    cwd: apiDir,
    encoding: "utf8",
    env: { ...process.env, PYTHONDONTWRITEBYTECODE: "1" },
  });
  const schemaFile = join(work, "openapi.json");
  writeFileSync(schemaFile, schema);

  const out = join(work, "api.d.ts");
  const bin = join(pkg, "node_modules", ".bin", "openapi-typescript");
  execFileSync(bin, [schemaFile, "--output", out, "--default-non-nullable", "false"], { stdio: ["ignore", "ignore", "inherit"] });

  const header =
    "// GENERATED by scripts/generate.mjs from the FastAPI OpenAPI schema. Do not edit.\n" +
    "// Regenerate: npm run generate (in packages/shared-types).\n";
  const fresh = header + readFileSync(out, "utf8");

  if (check) {
    const current = existsSync(target) ? readFileSync(target, "utf8") : "";
    if (current !== fresh) {
      console.error(
        "shared types drift: src/api.d.ts differs from the schema exported by the API.\n" +
          "Run `npm run generate` in packages/shared-types and commit the result.",
      );
      const diffFile = join(work, "expected.d.ts");
      writeFileSync(diffFile, fresh);
      try {
        execFileSync("diff", ["-u", target, diffFile], { stdio: "inherit" });
      } catch {
        // diff exits 1 when files differ; the output above is what we want.
      }
      process.exit(1);
    }
    console.log("shared types are up to date");
  } else {
    writeFileSync(target, fresh);
    console.log(`wrote ${target}`);
  }
} finally {
  rmSync(work, { recursive: true, force: true });
}
